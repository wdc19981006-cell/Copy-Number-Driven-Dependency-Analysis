Sys.setlocale("LC_CTYPE","English_United States.utf8")
source(".Rprofile");library(data.table)
args<-commandArgs(TRUE);a<-args[1];b<-args[2];root<-file.path("results",paste0(a,"_",b));prefix<-paste0(a,"_",b)
pair<-fread(file.path(root,"03_Targeted_Dependency",paste0(prefix,"_CellLines.csv")))
stats<-fread(file.path(root,"03_Targeted_Dependency",paste0(prefix,"_Statistics.csv")))
stopifnot(!anyDuplicated(pair$ModelID),all(is.finite(pair$CN_log)),all(is.finite(pair$Chronos)))
pe<-cor.test(pair$CN_log,pair$Chronos);sp<-cor.test(pair$CN_log,pair$Chronos,method="spearman",exact=FALSE)
wt<-wilcox.test(Chronos~CN_binary,data=pair,exact=FALSE)
close<-function(x,y)isTRUE(all.equal(as.numeric(x),as.numeric(y),tolerance=1e-12))
stopifnot(close(pe$estimate,stats$pearson_r),close(pe$p.value,stats$pearson_p),close(sp$estimate,stats$spearman_rho),close(wt$p.value,stats$wilcoxon_p))
screen<-fread(file.path(root,"02_GenomeWide_Dependency/GenomeWide_Dependency.csv"))
stopifnot(nrow(screen)==18531,!anyDuplicated(screen$Gene),identical(screen$Rank,seq_len(nrow(screen))))
stopifnot(close(p.adjust(screen$Wilcoxon_P,"BH"),screen$Wilcoxon_FDR),close(p.adjust(screen$Pearson_P,"BH"),screen$Pearson_FDR))
candidate<-screen[Gene==b];stopifnot(nrow(candidate)==1,close(candidate$N,nrow(pair)),close(candidate$Wilcoxon_P,wt$p.value),close(candidate$Pearson_r,pe$estimate))
delta<-with(pair,median(Chronos[CN_binary=="CN-Low"])-median(Chronos[CN_binary=="CN-NonLow"]))
stopifnot(close(candidate$Delta_median,delta))
cn<-fread(file.path(root,"03_Targeted_Dependency/Three_Group_Eligibility.csv"));if(any(cn$N<3))stopifnot(!file.exists(file.path(root,"03_Targeted_Dependency/Three_Group_Dependency.pdf")))
cat("PASS:",prefix,"targeted values, complete-screen BH, rank/candidate, group eligibility.\n")
